#!/usr/bin/env python3
"""Bundle HYDRA's ES modules into a classic script and a single-file HTML build.

The app is authored as native ES modules, which browsers refuse to load over
file://. The bundle lets index.html boot from a double-click.
"""
import json
import re
from pathlib import Path

ROOT = Path(__file__).parent
JS = ROOT / "js"
ENTRY = "script.js"

IMPORT_RE = re.compile(
    r"import\s*\{([^}]*)\}\s*from\s*['\"]\./?([A-Za-z0-9_./-]+)['\"]\s*;?",
    re.S,
)
EXPORT_NAMED_RE = re.compile(r"export\s*\{([^}]*)\}\s*;?")
EXPORT_DECL_RE = re.compile(
    r"export\s+(async\s+function|function|class|const|let|var)\s+([A-Za-z0-9_$]+)"
)
EXPORT_DEFAULT_RE = re.compile(
    r"^[ \t]*export\s+default\s+([A-Za-z0-9_$.]+)\s*;?[ \t]*$", re.M
)
IMPORT_DEFAULT_RE = re.compile(
    r"import\s+([A-Za-z0-9_$]+)\s+from\s+['\"]\.?/?([A-Za-z0-9_./-]+)['\"]\s*;?"
)


def module_id(path: str) -> str:
    return Path(path).stem


def transform(src: str):
    exports = []

    def repl_import(match):
        names = []
        for part in match.group(1).split(","):
            part = part.strip()
            if not part:
                continue
            if " as " in part:
                orig, alias = [p.strip() for p in part.split(" as ")]
                names.append(f"{orig}: {alias}")
            else:
                names.append(part)
        target = module_id(match.group(2))
        return f"const {{ {', '.join(names)} }} = __req('{target}');"

    src = IMPORT_DEFAULT_RE.sub(
        lambda m: f"const {{ default: {m.group(1)} }} = __req('{module_id(m.group(2))}');", src
    )
    src = IMPORT_RE.sub(repl_import, src)

    def repl_named(match):
        for part in match.group(1).split(","):
            part = part.strip()
            if not part:
                continue
            if " as " in part:
                orig, alias = [p.strip() for p in part.split(" as ")]
                exports.append(f"{alias}: {orig}")
            else:
                exports.append(part)
        return ""

    src = EXPORT_NAMED_RE.sub(repl_named, src)

    def repl_decl(match):
        kind, name = match.group(1), match.group(2)
        exports.append(name)
        return f"{kind} {name}"

    src = EXPORT_DECL_RE.sub(repl_decl, src)
    def repl_default(match):
        exports.append(f"default: {match.group(1)}")
        return ""

    src = EXPORT_DEFAULT_RE.sub(repl_default, src)

    body = "return { " + ", ".join(exports) + " };" if exports else "return {};"
    return src + "\n" + body + "\n"


def build_js() -> str:
    modules = sorted(p for p in JS.glob("*.js"))
    chunks = [
        "/* HYDRA bundle — generated by build.py. Do not edit. */",
        "(function () {",
        "'use strict';",
        "var __mods = Object.create(null), __cache = Object.create(null);",
        "function __def(id, fn) { __mods[id] = fn; }",
        "function __req(id) {",
        "  if (__cache[id]) return __cache[id];",
        "  var fn = __mods[id];",
        "  if (!fn) throw new Error('Missing module: ' + id);",
        "  __cache[id] = fn();",
        "  return __cache[id];",
        "}",
    ]
    for path in modules:
        mid = path.stem
        chunks.append(f"__def({json.dumps(mid)}, function () {{")
        chunks.append(transform(path.read_text()))
        chunks.append("});")
    entry = (ROOT / ENTRY).read_text()
    chunks.append("__def('__entry', function () {")
    chunks.append(transform(entry))
    chunks.append("});")
    chunks.append("__req('__entry');")
    chunks.append("})();")
    return "\n".join(chunks)


CSS_ORDER = [
    "style.css",
    "css/themes.css",
    "css/animations.css",
    "css/dashboard.css",
    "css/widgets.css",
    "css/ai.css",
    "css/cv.css",
    "css/world.css",
    "css/extras.css",
    "css/auth.css",
    "css/motion.css",
    "css/pack.css",
    "css/mobile.css",
]


def build_html(js: str) -> str:
    html = (ROOT / "index.html").read_text()
    css = "\n".join((ROOT / name).read_text() for name in CSS_ORDER)
    html = re.sub(r'\s*<link rel="stylesheet"[^>]*>', "", html)
    html = re.sub(
        r"\s*<script type=\"module\" src=\"script.js\"></script>", "", html
    )
    # The single-file build inlines the bundle, so the file:// loader is not needed
    # and would try to fetch a sibling file that Chrome refuses to load.
    html = re.sub(
        r"<script>\s*// file:// blocks ES module imports[\s\S]*?</script>\s*", "", html, count=1
    )
    html = html.replace(
        "</head>", f"<style>\n{css}\n</style>\n</head>", 1
    )
    # config.js and nav.js are plain scripts; a file:// page cannot fetch them,
    # so inline both. The nav bar is markup the bundle does not own.
    html = re.sub(r'\s*<script src="js/config\.js"></script>', "", html)
    html = re.sub(r'\s*<script src="js/nav\.js" defer></script>', "", html)
    config = (JS / "config.js").read_text()
    nav = (JS / "nav.js").read_text()
    # The switcher is an ES module; strip the module syntax so it can run inline
    # against the bundle's universal instance exposed on window.
    switcher = (JS / "app-switcher.js").read_text()
    switcher = switcher.replace("import universal from './universal.js';", "const universal = window.hydraUniversal;")
    switcher = switcher.replace("export async function initAppSwitcher", "async function initAppSwitcher")
    switcher = switcher.replace("export default initAppSwitcher;", "")
    switcher += "\ninitAppSwitcher({ currentApp: 'companion', mount: document.getElementById('hydra-nav-switch') }).catch(() => {});\n"
    html = html.replace(
        "</head>", f"<script>\n{config}\n</script>\n</head>", 1
    )
    html = html.replace(
        "</body>", f"<script>\n{js}\n</script>\n<script>\n{switcher}\n</script>\n<script>\n{nav}\n</script>\n</body>", 1
    )
    return html


def sync_versions():
    """Keep the service worker cache name in step with the app version."""
    version = re.search(
        r"export const VERSION = '([^']+)'", (JS / "updater.js").read_text()
    ).group(1)
    sw = ROOT / "sw.js"
    text = re.sub(r"const CACHE = 'hydra-v[^']+';", f"const CACHE = 'hydra-v{version}';", sw.read_text())
    sw.write_text(text)
    return version


def main():
    sync_versions()
    js = build_js()
    (ROOT / "hydra.bundle.js").write_text(js)
    (ROOT / "HYDRA.html").write_text(build_html(js))
    print(f"bundle: {len(js):,} bytes, html: {(ROOT / 'HYDRA.html').stat().st_size:,} bytes")


if __name__ == "__main__":
    main()
